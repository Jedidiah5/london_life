import fs from "node:fs";

const catalogue = JSON.parse(fs.readFileSync("data/catalogue.json", "utf8"));
const jobs = JSON.parse(fs.readFileSync("data/jobs.json", "utf8"));
const homes = JSON.parse(fs.readFileSync("data/homes.json", "utf8"));
const venues = JSON.parse(fs.readFileSync("data/venues.json", "utf8"));
const { actions } = JSON.parse(fs.readFileSync("data/actions.json", "utf8"));
const goals = JSON.parse(fs.readFileSync("data/goals.json", "utf8"));
const locals = JSON.parse(fs.readFileSync("data/locals.json", "utf8"));

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const textArray = (values) => `array[${values.map(quote).join(", ")}]::text[]`;
const nullable = (value, wrap = quote) => (value === undefined || value === null ? "null" : wrap(value));

const base = [
  "-- Seed data. Run after 001_london_life.sql. Generated by scripts/emit-seed.mjs",
  "",
  "insert into homes (id, name, zone, width, height, rent_pence, buy_pence) values",
  homes
    .map(
      (home) =>
        `(${[quote(home.id), quote(home.name), home.zone, home.width, home.height, home.rentPence, home.buyPence === null ? "null" : home.buyPence].join(", ")})`,
    )
    .join(",\n") + " on conflict (id) do nothing;",
  "",
  "insert into venues (id, name, zone) values",
  venues.map((venue) => `(${[quote(venue.id), quote(venue.name), venue.zone].join(", ")})`).join(",\n") +
    " on conflict (id) do update set name = excluded.name;",
  "",
  "insert into catalogue_items (id, name, category, footprint, wall, price_pence, tier, blocks, effects) values",
  catalogue
    .map((item) => {
      const wall = item.footprint === "wall";
      const footprint = wall ? "null" : `'{${item.footprint.join(",")}}'`;
      const effects = json({ effect: item.effect, menu: item.menu });
      return `(${[quote(item.id), quote(item.name), quote(item.category), footprint, wall, item.pricePence, item.tier, item.blocks, effects].join(", ")})`;
    })
    .join(",\n") + " on conflict (id) do update set effects = excluded.effects;",
  "",
  "insert into jobs (id, name, venue, pay_per_hour_pence, hours, skill, skill_required, energy_cost, xp_skill, tips) values",
  jobs
    .map(
      (job) =>
        `(${[quote(job.id), quote(job.name), quote(job.venue), job.payPerHourPence, job.hours, job.skill ? quote(job.skill) : "null", job.skillRequired, job.energyCost, quote(job.xpSkill), job.tips].join(", ")})`,
    )
    .join(",\n") +
    " on conflict (id) do update set name = excluded.name, venue = excluded.venue, pay_per_hour_pence = excluded.pay_per_hour_pence, hours = excluded.hours, skill = excluded.skill, skill_required = excluded.skill_required, energy_cost = excluded.energy_cost, xp_skill = excluded.xp_skill, tips = excluded.tips;",
  "",
];

const story = [
  "-- Story data for 003_story.sql. Generated by scripts/emit-seed.mjs",
  "",
  ...homes.map(
    (home) =>
      `update homes set fixtures = ${json(home.fixtures.map(({ id, itemId, x, y, rotation, blocks, label }) => ({ id, itemId, x, y, rotation, blocks, label, footprint: footprintOf(itemId) })))} where id = ${quote(home.id)};`,
  ),
  "",
  ...jobs.map((job) => `update jobs set ladder = ${textArray(job.ladder)} where id = ${quote(job.id)};`),
  "",
  "insert into actions (id, cost_pence, minutes, effects, skill, xp, requires_skill, requires_level, venue, anywhere, heritage, scales) values",
  Object.entries(actions)
    .map(([id, action]) =>
      `(${[
        quote(id),
        action.costPence,
        action.minutes,
        json(action.effects),
        nullable(action.skill),
        action.xp ?? 0,
        nullable(action.requires?.skill),
        action.requires?.level ?? 0,
        nullable(action.venue),
        action.anywhere === true,
        action.heritage === true,
        action.scales === true,
      ].join(", ")})`,
    )
    .join(",\n") +
    " on conflict (id) do update set cost_pence = excluded.cost_pence, minutes = excluded.minutes, effects = excluded.effects, skill = excluded.skill, xp = excluded.xp, requires_skill = excluded.requires_skill, requires_level = excluded.requires_level, venue = excluded.venue, anywhere = excluded.anywhere, heritage = excluded.heritage, scales = excluded.scales;",
  "",
  "insert into goals (id, ordinal, stat, count, reward_pence) values",
  goals.map((goal, index) => `(${[quote(goal.id), index, quote(goal.stat), goal.count, goal.rewardPence].join(", ")})`).join(",\n") +
    " on conflict (id) do update set ordinal = excluded.ordinal, stat = excluded.stat, count = excluded.count, reward_pence = excluded.reward_pence;",
  "",
  "insert into locals (id, venues) values",
  locals.map((local) => `(${quote(local.id)}, ${textArray(local.venues)})`).join(",\n") +
    " on conflict (id) do update set venues = excluded.venues;",
  "",
];

function footprintOf(itemId) {
  const item = catalogue.find((entry) => entry.id === itemId);
  return item && item.footprint !== "wall" ? item.footprint : [1, 1];
}

fs.writeFileSync("supabase/migrations/002_seed.sql", base.join("\n"));
fs.writeFileSync("supabase/migrations/004_story_seed.sql", story.join("\n"));
console.log(`catalogue ${catalogue.length}, jobs ${jobs.length}, actions ${Object.keys(actions).length}, locals ${locals.length}`);
